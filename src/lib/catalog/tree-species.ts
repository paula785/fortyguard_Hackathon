export function getSpeciesById(id: string): TreeSpecies | undefined {
  return TREE_SPECIES.find((s) => s.id === id);
}

export function filterSpeciesByClimate(zone: ClimateZone): TreeSpecies[] {
  return TREE_SPECIES.filter((s) => s.climateZones.includes(zone));
}

export function filterSpeciesByDrought(minTolerance: DroughtTolerance): TreeSpecies[] {
  const order: DroughtTolerance[] = ["low", "medium", "high", "very-high"];
  const minIdx = order.indexOf(minTolerance);
  return TREE_SPECIES.filter((s) => order.indexOf(s.droughtTolerance) >= minIdx);
}
